#[derive(Copy, Clone, Debug)]
pub enum Register {
    X86(RegisterX86),
    RISCV(RegisterRISCV),
}

impl From<RegisterX86> for Register {
    fn from(reg: RegisterX86) -> Self {
        Register::X86(reg)
    }
}

impl From<RegisterRISCV> for Register {
    fn from(reg: RegisterRISCV) -> Self {
        Register::RISCV(reg)
    }
}

