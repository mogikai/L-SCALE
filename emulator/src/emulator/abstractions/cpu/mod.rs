#[derive(Error, Debug, Copy, Clone)]
pub enum CPUError {
    #[error("TODO")]
    InvalidArch,
    #[error("TODO")]
    InvalidPermission,
    #[error("TODO")]
    Stopped(StopReason),
    #[error("TODO")]
    TaskExists,
    #[error("TODO")]
    Unknown,
}

pub type ContextHandle = u64;

pub trait CPU: Restorable {
    /// # Arguments
    /// * `stop`: A virtual address to stop execution at. If zero is passed as address, the emulation will not stop.
    /// * `timeout`: The emulation will stop after the supplied duration.
    /// * `instruction_count`: The emulation will stop after the supplied number of instructions.
    ///
    /// returns: A CPUError if an error occurred during emulation.
    ///          In most cases such an error will correspond to a segfault.
    fn emulate(
        &mut self,
        stop: Option<EVAddr>,
        timeout: Option<Duration>,
        instruction_count: Option<usize>,
    ) -> Result<(), CPUError>;

    fn stop(
        &mut self,
        stop_reason: StopReason,
    ) -> Result<(), CPUError>;

    fn reg_write(
        &mut self,
        register: Register,
        value: u64,
    ) -> Result<(), CPUError>;

    fn reg_read(
        &self,
        register: Register,
    ) -> Result<u64, CPUError>;

    fn add_breakpoint(
        &mut self,
        address: EVAddr,
    ) -> Result<(), CPUError>;

    fn remove_breakpoint(
        &mut self,
        address: EVAddr,
    ) -> Result<(), CPUError>;

    fn create_context(&mut self) -> Result<ContextHandle, CPUError>;

    fn save_context(
        &mut self,
        context_handle: ContextHandle,
    ) -> Result<(), CPUError>;

    fn restore_context(
        &mut self,
        context_handle: ContextHandle,
    ) -> Result<(), CPUError>;

    fn remove_context(
        &mut self,
        context_handle: ContextHandle,
    ) -> Result<(), CPUError>;
}

impl From<TryFromIntError> for CPUError {
    fn from(_: TryFromIntError) -> Self {
        CPUError::InvalidPermission
    }
}

